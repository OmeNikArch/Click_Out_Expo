def site(u):
 u=(u or '').strip().split()[0] if (u or '').strip() else ''
 if not re.match(r'^https?://[^/@]+\.[^/@]+',u) or '@' in urlsplit(u).netloc: return ''
 return u

def rows():
 if not RAW.exists():
  RAW.parent.mkdir(parents=True,exist_ok=True)
  req=urllib.request.Request('https://pirexpo.com/api/v3/brand/list?project=14',headers={'User-Agent':'Mozilla/5.0'})
  RAW.write_bytes(urllib.request.urlopen(req,timeout=60).read())
 raw=json.loads(RAW.read_text(encoding='utf-8'))
 probes={SNAPSHOT_IDS.get(r['id']):r for r in json.loads(PROBES.read_text(encoding='utf-8'))} if PROBES.exists() else {}
 out=[]
 for i,x in enumerate(raw):
  booths=[b for b in x.get('booths',[]) if b.get('published') and b.get('booth_number')]
  one=booths[0] if booths else {}
  hall=str(one.get('hall_number') or '')
  stand=', '.join(dict.fromkeys(b['booth_number'] for b in booths))
  brand_id=x['id']
  mp=probes.get(brand_id,{}).get('marketplace',[]) or ([CONFIRMED_MP[brand_id]] if brand_id in CONFIRMED_MP else [])
  if brand_id in DIRECT and stand: prio,reason='A',DIRECT[brand_id]
  elif brand_id in PRIORITY_BRANDS and stand:prio,reason='A',PRIORITY_BRANDS[brand_id]
  elif brand_id in QUALIFY and stand:prio,reason='B',QUALIFY[brand_id]
  else:
   prio='C'
   reason='Стенд не указан' if not stand else 'Поставщик HoReCa / B2B либо B2C не подтверждён'
  cats=[c['name'] for c in x.get('catalog_classificator',[]) if c.get('name')][:3]
  descr=re.sub(r'\s+',' ',x.get('description') or '').strip()[:300]
  rec={'id':x['id'],'hall':hall,'stand':stand,'name':x['name'].strip(),'country':'Россия / не указана',
   'city':'','site':site(x.get('website')),'profile':cats,'descr':descr,
   'products':[p.get('name','')[:75] for p in x.get('products',[])[:2]],'hl':[reason[:95]],'brands':[],
   'tags':[('прямой заказ/бронь' if brand_id in DIRECT else 'брендформанс') if prio=='A' else ('проверить марку' if prio=='B' else 'вне маршрута')]+(['ссылка на МП — кто селлер?' ] if mp else [])+(['стенда нет'] if not stand else []),
   'prio':prio,'top':brand_id in DIRECT or brand_id in STAR_BRANDS,'meta':reason,
   '_phones':[x['phone']] if x.get('phone') else [],'_emails':[x['email']] if x.get('email') else []}
  out.append(rec)
 return sorted(out,key=lambda r:({'A':0,'B':1,'C':2}[r['prio']],r['hall'],r['stand'],r['name']))

